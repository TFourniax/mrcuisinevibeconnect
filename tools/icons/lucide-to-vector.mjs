// Converts Lucide icons (ISC, https://lucide.dev, licence in LUCIDE-LICENSE.txt) into Android
// VectorDrawable XML for the dish placeholders (app/src/main/res/drawable/dish_*.xml).
// Android 6 inflates VectorDrawable natively: stroke only, 24×24, white (tinted in code).
//
//   node tools/icons/lucide-to-vector.mjs <lucide-react>/dist/esm/icons app/src/main/res/drawable
//
// The icon list matches app.toque.core.recipes.DishKind.
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const ICONS = [
  "soup", "salad", "fish", "beef", "drumstick", "egg-fried", "cooking-pot", "pizza", "croissant",
  "cake-slice", "cookie", "ice-cream-cone", "cup-soda", "coffee", "wine", "carrot", "citrus", "sandwich", "chef-hat",
];

const [src, out] = process.argv.slice(2);
if (!src || !out) {
  console.error("usage: node lucide-to-vector.mjs <lucide icons dir> <drawable dir>");
  process.exit(1);
}

const n = (v) => Number(v ?? 0);

// Path data rewritten with explicit separators: Android 6's parser misreads compact forms such
// as arc flags written together ("a1 1 0 00-.99 1.133") or numbers sharing a dot (".06.83").
const ARITY = { m: 2, l: 2, t: 2, h: 1, v: 1, c: 6, s: 4, q: 4, a: 7, z: 0 };
function normalizePath(d) {
  let i = 0;
  const out = [];
  const skip = () => {
    while (i < d.length && /[\s,]/.test(d[i])) i++;
  };
  const number = () => {
    skip();
    const m = /^[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?/.exec(d.slice(i));
    if (!m) throw new Error(`bad number at ${i} in ${d}`);
    i += m[0].length;
    return fmt(Number(m[0]));
  };
  const flag = () => {
    skip();
    const c = d[i];
    if (c !== "0" && c !== "1") throw new Error(`bad arc flag at ${i} in ${d}`);
    i++;
    return c;
  };
  while (true) {
    skip();
    if (i >= d.length) break;
    const cmd = d[i];
    const arity = ARITY[cmd.toLowerCase()];
    if (arity === undefined) throw new Error(`unknown command ${cmd} in ${d}`);
    i++;
    if (arity === 0) {
      out.push(cmd);
      continue;
    }
    let first = true;
    do {
      const args = [];
      for (let k = 0; k < arity; k++) args.push(cmd.toLowerCase() === "a" && (k === 3 || k === 4) ? flag() : number());
      out.push((first ? cmd : "") + args.join(" "));
      first = false;
      skip();
    } while (i < d.length && /[-+.\d]/.test(d[i]));
  }
  return out.join(" ");
}
const fmt = (v) => String(Math.round(v * 1000) / 1000);

// Every Lucide element as SVG path data.
function pathOf([tag, a]) {
  switch (tag) {
    case "path":
      return a.d;
    case "circle": {
      const cx = n(a.cx), cy = n(a.cy), r = n(a.r);
      return `M${fmt(cx - r)} ${fmt(cy)}a${fmt(r)} ${fmt(r)} 0 1 0 ${fmt(2 * r)} 0a${fmt(r)} ${fmt(r)} 0 1 0 ${fmt(-2 * r)} 0`;
    }
    case "ellipse": {
      const cx = n(a.cx), cy = n(a.cy), rx = n(a.rx), ry = n(a.ry);
      return `M${fmt(cx - rx)} ${fmt(cy)}a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(2 * rx)} 0a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(-2 * rx)} 0`;
    }
    case "line":
      return `M${fmt(n(a.x1))} ${fmt(n(a.y1))}L${fmt(n(a.x2))} ${fmt(n(a.y2))}`;
    case "polyline":
    case "polygon": {
      const pts = a.points.trim().split(/[\s,]+/).map(Number);
      let d = `M${fmt(pts[0])} ${fmt(pts[1])}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${fmt(pts[i])} ${fmt(pts[i + 1])}`;
      return tag === "polygon" ? d + "Z" : d;
    }
    case "rect": {
      const x = n(a.x), y = n(a.y), w = n(a.width), h = n(a.height);
      const rx = Math.min(n(a.rx ?? a.ry), w / 2), ry = Math.min(n(a.ry ?? a.rx), h / 2);
      if (!rx && !ry) return `M${fmt(x)} ${fmt(y)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}Z`;
      return (
        `M${fmt(x + rx)} ${fmt(y)}h${fmt(w - 2 * rx)}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(rx)} ${fmt(ry)}` +
        `v${fmt(h - 2 * ry)}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(-rx)} ${fmt(ry)}h${fmt(-(w - 2 * rx))}` +
        `a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(-rx)} ${fmt(-ry)}v${fmt(-(h - 2 * ry))}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(rx)} ${fmt(-ry)}Z`
      );
    }
    default:
      throw new Error(`unsupported element <${tag}>`);
  }
}

for (const name of ICONS) {
  const mod = await import(pathToFileURL(resolve(src, `${name}.mjs`)).href);
  const nodes = mod.__iconData.node;
  const paths = nodes
    .map(
      (node) =>
        `    <path\n        android:pathData="${normalizePath(pathOf(node))}"\n        android:strokeColor="#FFFFFFFF"\n` +
        `        android:strokeWidth="2"\n        android:strokeLineCap="round"\n        android:strokeLineJoin="round" />`,
    )
    .join("\n");
  const xml =
    `<?xml version="1.0" encoding="utf-8"?>\n` +
    `<!-- Lucide "${name}" (ISC licence, tools/icons/LUCIDE-LICENSE.txt). Generated by tools/icons/lucide-to-vector.mjs. -->\n` +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n` +
    `    android:width="24dp"\n    android:height="24dp"\n    android:viewportWidth="24"\n    android:viewportHeight="24">\n` +
    `${paths}\n</vector>\n`;
  const file = join(out, `dish_${name.replace(/-/g, "_")}.xml`);
  writeFileSync(file, xml);
  console.log(file, nodes.map((x) => x[0]).join(","));
}
